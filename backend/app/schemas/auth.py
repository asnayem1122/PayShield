"""Authentication request and response schemas conforming to PayShield standards."""

from datetime import datetime
import uuid
from pydantic import BaseModel, ConfigDict, Field, field_validator


class LoginRequest(BaseModel):
    """Credentials payload for authenticating a user."""

    email: str = Field(..., description="User email address")
    password: str = Field(..., min_length=1, description="Raw user password")

    @field_validator("email")
    @classmethod
    def normalize_email(cls, v: str) -> str:
        clean = v.strip().lower()
        if not clean or "@" not in clean:
            raise ValueError("Invalid email address format")
        return clean


class RefreshTokenRequest(BaseModel):
    """Payload for rotating an expired access token using a refresh token."""

    refresh_token: str = Field(..., min_length=1, description="Current refresh token")


class UserSummaryResponse(BaseModel):
    """Lightweight user identity representation for auth responses."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    email: str
    full_name: str
    role: str
    status: str
    merchant_id: uuid.UUID | None = None
    merchant_name: str | None = None


class UserProfileResponse(BaseModel):
    """Complete user profile information for the /auth/me endpoint."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    email: str
    full_name: str
    role: str
    status: str
    merchant_id: uuid.UUID | None = None
    merchant_name: str | None = None
    last_login_at: datetime | None = None
    created_at: datetime


class TokenResponse(BaseModel):
    """RFC 6749 compliant token response payload."""

    access_token: str
    refresh_token: str
    token_type: str = "Bearer"
    expires_in: int = Field(
        ..., description="Access token expiration duration in seconds"
    )
    user: UserSummaryResponse


class ProblemDetail(BaseModel):
    """RFC 9457 compliant problem detail error format."""

    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type",
    )
    title: str = Field(..., description="A short human-readable summary of the problem")
    status: int = Field(..., description="The HTTP status code generated by the origin")
    detail: str = Field(
        ..., description="A human-readable explanation specific to this occurrence"
    )
    instance: str | None = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence",
    )
